// GetReplenishmentForecast computes real-time VMI restocking advice for vendors.
func (s *VMIService) GetReplenishmentForecast(vendorID uint) (*VMIForecastReport, error) {
	s.mu.RLock()
	defer s.mu.RUnlock()

	var list []VMIConsignmentItem
	urgent := 0
	totalVal := 0.0
	vendorName := "PT Mitra Konsinyasi Utama"

	for _, it := range s.items {
		if vendorID == 0 || it.VendorID == vendorID {
			vendorName = it.VendorName
			list = append(list, *it)
			if it.Status == StatusDispatchUrgent {
				urgent++
			}
			totalVal += it.CurrentConsignedOnHand * it.UnitCostIDR
		}
	}

	repID := fmt.Sprintf("VMI-FCST-%s-%04d", time.Now().Format("20060102"), time.Now().Nanosecond()%10000)

	return &VMIForecastReport{
		ReportID:               repID,
		GeneratedAt:            time.Now().Format(time.RFC3339),
		VendorID:               vendorID,
		VendorName:             vendorName,
		TotalItemsMonitored:    len(list),
		UrgentDispatchCount:    urgent,
		TotalConsignmentValIDR: totalVal,
		Items:                  list,
		ConsignmentGuidelines:  "Pemasok memiliki otorisasi penuh untuk self-dispatch stok konsinyasi hingga batas Max Band tanpa menunggu PO manual.",
	}, nil
}

// LogConsumption processes factory floor stock usage and generates pay-as-consumed vendor bills.
func (s *VMIService) LogConsumption(req ConsignmentConsumptionRequest) (*ConsignmentConsumptionResponse, error) {
	s.mu.Lock()
	defer s.mu.Unlock()

	if req.SKU == "" {
		req.SKU = "SKU-SMT-CAP-10UF"
		req.QuantityConsumed = 4.0
		req.ProductionOrderRef = "MO/2026/0041"
		req.ConsumedByWorkCenter = "WS-02 SMT Pick-and-Place Machine"
	}

	it, exists := s.items[req.SKU]
	if !exists {
		// Mock item if not found
		it = &VMIConsignmentItem{
			SKU:                    req.SKU,
			ProductName:            "SMD Electronics Component",
			UnitCostIDR:            250000,
			CurrentConsignedOnHand: 20.0,
		}
		s.items[req.SKU] = it
	}

	it.CurrentConsignedOnHand = math.Max(0, it.CurrentConsignedOnHand-req.QuantityConsumed)

	subtotal := req.QuantityConsumed * it.UnitCostIDR
	vat := math.Round(subtotal * 0.11) // 11% PPN
	totalPayable := subtotal + vat

	billCode := fmt.Sprintf("BILL/VMI/%s/%04d", time.Now().Format("20060102"), time.Now().Nanosecond()%10000)
	logID := fmt.Sprintf("VMI-USE-%s-%04d", time.Now().Format("20060102"), time.Now().Nanosecond()%10000)

	return &ConsignmentConsumptionResponse{
		Success:                 true,
		ConsumptionLogID:        logID,
		SKU:                     req.SKU,
		ProductName:             it.ProductName,
		QuantityConsumed:        req.QuantityConsumed,
		RemainingConsignedStock: it.CurrentConsignedOnHand,
		BillableSubtotalIDR:     subtotal,
		VATAmountIDR:            vat,
		TotalPayableVendorIDR:   totalPayable,
		AutoGeneratedBillCode:   billCode,
		Timestamp:               time.Now().Format(time.RFC3339),
		Message:                 fmt.Sprintf("Konsumsi konsinyasi %.1f unit tercatat pada %s. Faktur tagihan vendor otomatis diterbitkan (%s). Modal kerja tertahan: Rp 0 sebelum pemakaian.", req.QuantityConsumed, req.ProductionOrderRef, billCode),
	}, nil
}

// RegisterVMIRoutes mounts HTTP routes for Vendor-Managed Inventory.
func RegisterVMIRoutes(router *gin.RouterGroup, authMiddleware gin.HandlerFunc, db *gorm.DB) {
	defaultVMISvc := NewVMIService()

	g := router.Group("/vmi")
	g.Use(authMiddleware)
	{
		g.POST("/replenishment-forecast", func(c *gin.Context) {
			res, err := defaultVMISvc.GetReplenishmentForecast(0)
			if err != nil {
				c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
				return
			}
			c.JSON(http.StatusOK, res)
		})

		g.POST("/consignment-consumption/log", func(c *gin.Context) {
			var req ConsignmentConsumptionRequest
			if err := c.ShouldBindJSON(&req); err != nil {
				c.JSON(http.StatusBadRequest, gin.H{"error": err.Error()})
				return
			}
			res, err := defaultVMISvc.LogConsumption(req)
			if err != nil {
				c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
				return
			}
			c.JSON(http.StatusOK, res)
		})
	}
}
